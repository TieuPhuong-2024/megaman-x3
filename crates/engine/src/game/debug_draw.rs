use crate::physics::Aabb;
use crate::render::SpriteDraw;

pub fn push_filled_rect(sprites: &mut Vec<SpriteDraw>, x: f32, y: f32, w: f32, h: f32, color: [f32; 4]) {
    sprites.push(SpriteDraw {
        texture: 0,
        x,
        y,
        w,
        h,
        u0: 0.0,
        v0: 0.0,
        u1: 1.0,
        v1: 1.0,
        color,
        flip_x: false,
    });
}

pub fn push_box_outline(sprites: &mut Vec<SpriteDraw>, box_: Aabb, color: [f32; 4]) {
    let w = box_.right - box_.left;
    let h = box_.top - box_.bottom;
    let t = 2.0;
    let edges = [
        (box_.left, box_.bottom, w, t),
        (box_.left, box_.top - t, w, t),
        (box_.left, box_.bottom, t, h),
        (box_.right - t, box_.bottom, t, h),
    ];
    for (x, y, ew, eh) in edges {
        push_filled_rect(sprites, x, y, ew, eh, color);
    }
}

pub fn draw_text(sprites: &mut Vec<SpriteDraw>, x: f32, y: f32, text: &str, color: [f32; 4]) {
    let mut cursor = x;
    for ch in text.chars() {
        if let Some(rows) = glyph(ch) {
            for (row_i, row) in rows.iter().enumerate() {
                for col in 0..5 {
                    if row & (1 << (4 - col)) != 0 {
                        sprites.push(SpriteDraw {
                            texture: 0,
                            x: cursor + col as f32 * 3.0,
                            y: y + (6 - row_i) as f32 * 3.0,
                            w: 2.5,
                            h: 2.5,
                            u0: 0.0,
                            v0: 0.0,
                            u1: 1.0,
                            v1: 1.0,
                            color,
                            flip_x: false,
                        });
                    }
                }
            }
        }
        cursor += 6.5;
    }
}

